/** Normalises `keyFindings`/`anomalies`/`recommendations`/`warnings`/`limitations` (each `unknown` on the DTO) into display strings. */
export function toTextList(raw: unknown): string[] {
  return asArray(raw)
    .map((item) => {
      if (typeof item === "string") return item;
      if (item && typeof item === "object") {
        const record = item as Record<string, unknown>;
        const text = record.message ?? record.description ?? record.text ?? record.label;
        return typeof text === "string" ? text : JSON.stringify(item);
      }
      return null;
    })
    .filter((v): v is string => v !== null && v.trim() !== "");
}

export interface WarningClassification {
  title: string;
  tone: StatusTone;
}

/**
 * Classifies (not rewrites) a warning string for presentation — icon/tone/
 * kicker only. The wording shown to the user is always the original text
 * (Part 7: "do not change the actual warning text"). Rules match the exact
 * warning phrasing the current worker produces (Aqua-Blend-Analysis-Ai/AI/
 * main.py, results/app_response/examples/fallback_response.json) plus a safe
 * default for any warning text this frontend doesn't recognise.
 */
const WARNING_RULES: ReadonlyArray<{ match: (text: string) => boolean; title: string; tone: StatusTone }> = [
  { match: (t) => t.includes("confidence could not be determined"), title: "Confidence", tone: "warning" },
  { match: (t) => t.includes("estimated value"), title: "Estimated source data", tone: "warning" },
  { match: (t) => t.includes("activation cost") && t.includes("zero"), title: "Cost modelling note", tone: "info" },
  { match: (t) => t.includes("water-quality") || t.includes("plant inflow"), title: "Water-quality scope", tone: "info" },
  {
    match: (t) => t.includes("validated llm explanation") || t.includes("deterministic template") || t.includes("model rewrite fell back"),
    title: "Analysis mode",
    tone: "info",
  },
  { match: (t) => t.includes("llm validation warning") || t.includes("rejected by validation"), title: "Analysis mode", tone: "warning" },
  { match: (t) => t.includes("no optimal-solution") || t.includes("optimal-solution metrics"), title: "Result availability", tone: "warning" },
  { match: (t) => t.includes("validation failed") || t.includes("invalid input"), title: "Data quality", tone: "danger" },
];

export function classifyWarning(text: string): WarningClassification {
  const lower = text.toLowerCase();
  for (const rule of WARNING_RULES) {
    if (rule.match(lower)) return { title: rule.title, tone: rule.tone };
  }
  return { title: "Notice", tone: "warning" };
}
